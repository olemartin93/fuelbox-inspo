export const questions: readonly Question[] = (Object.keys(raw) as CategoryId[]).flatMap((categoryId) =>
  raw[categoryId].map((text, i) => ({ id: `${categoryId}-${i + 1}`, categoryId, text })),
);

export function getQuestionsForCategory(categoryId: CategoryId): readonly Question[] {
  return questions.filter((q) => q.categoryId === categoryId);
}
